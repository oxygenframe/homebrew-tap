#!/usr/bin/env bash
# Writes Formula/oxframe.rb for the latest oxframe-cli release (or the
# version given as $1), from the archives and .sha256 files the release
# workflow uploads. Run by .github/workflows/update.yml.
set -euo pipefail
repo=oxygenframe/oxframe-cli
version=${1:-$(curl -sSf "https://api.github.com/repos/$repo/releases/latest" | jq -r .tag_name)}
version=${version#v}
sum() {
  curl -sSfL "https://github.com/$repo/releases/download/v$version/oxframe-v$version-$1.tar.gz.sha256" | cut -d' ' -f1
}
url="https://github.com/$repo/releases/download/v$version/oxframe-v$version"
cat > Formula/oxframe.rb <<RUBY
# Generated by update.sh from the oxframe-cli v$version release; do not edit.
class Oxframe < Formula
  desc "Make videos from Rust code: preview with hot reload, render, check"
  homepage "https://oxframe.dev"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$url-aarch64-apple-darwin.tar.gz"
      sha256 "$(sum aarch64-apple-darwin)"
    end
    on_intel do
      url "$url-x86_64-apple-darwin.tar.gz"
      sha256 "$(sum x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$url-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum aarch64-unknown-linux-gnu)"
    end
    on_intel do
      url "$url-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum x86_64-unknown-linux-gnu)"
    end
  end

  depends_on "ffmpeg"

  def install
    bin.install "oxframe"
  end

  def caveats
    <<~EOS
      oxframe builds your project with cargo. If you do not have Rust yet:
        curl https://sh.rustup.rs -sSf | sh
      Then: oxframe init my-video && cd my-video && oxframe dev --open
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/oxframe --version")
  end
end
RUBY
echo "Formula/oxframe.rb: $version"
